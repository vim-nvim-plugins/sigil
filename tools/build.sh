#!/bin/sh
# build.sh — fetch the pinned sources in grammars.txt, assemble each language's locals query,
# compile everything into one static binary: bin/sigil. Run through `make`.
#   CC, CFLAGS, JOBS from the environment. Sources are cached in deps/ (delete it to refetch).
set -eu
cd "$(dirname "$0")/.."
CC=${CC:-cc}
CFLAGS=${CFLAGS:--O2}
JOBS=${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}
mkdir -p deps build/obj build/queries bin

fetch() {	# fetch <dir> <owner/repo> <rev>
	[ "$(cat "deps/$1/.rev" 2>/dev/null)" = "$3" ] && return 0
	echo "fetch $2 @ $3"
	rm -rf "deps/$1" && mkdir -p "deps/$1"
	curl -fsSL "https://github.com/$2/archive/$3.tar.gz" | tar -xz -C "deps/$1" --strip-components=1
	echo "$3" > "deps/$1/.rev"
}

pin() { awk -v k="$1" '$1 == k { print $2, $3 }' grammars.txt; }
langs() { awk '!/^#/ && NF >= 5 && $1 !~ /^[A-Z_]+$/' grammars.txt; }

set -- $(pin TREE_SITTER); fetch tree-sitter "$1" "$2"
set -- $(pin NVTS);        fetch nvts "$1" "$2"
langs | while read -r name repo rev sub aliases; do fetch "g-$name" "$repo" "$rev"; done

# locals query = its "; inherits:" bases first, then its own patterns, then sigil's fixes for
# that language from queries/<lang>.scm (patterns upstream lacks; see the comments there)
query() (	# subshell: the recursion must not clobber $f
	f="deps/nvts/runtime/queries/$1/locals.scm"
	[ -f "$f" ] || { echo "no locals query for $1 in nvim-treesitter" >&2; exit 1; }
	for base in $(sed -n '1s/^; inherits: *//p' "$f" | tr ',' ' ' | tr -d '()'); do query "$base"; done
	sed '1{/^; inherits:/d;}' "$f"
	[ ! -f "queries/$1.scm" ] || cat "queries/$1.scm"
)

gen=build/langs.c
{
	echo '/* generated by tools/build.sh from grammars.txt — do not edit */'
	echo '#include <tree_sitter/api.h>'
	echo 'typedef struct { const char *name; const TSLanguage *(*language)(void); const char *query; const char *aliases; } Grammar;'
	langs | while read -r name repo rev sub aliases; do
		query "$name" > "build/queries/$name.scm"
		echo "const TSLanguage *tree_sitter_$name(void);"
		echo "static const char q_$name[] ="
		sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/"/' -e 's/$/\\n"/' "build/queries/$name.scm"
		echo ";"
	done
	echo 'const Grammar sigil_grammars[] = {'
	langs | while read -r name repo rev sub aliases; do echo "	{\"$name\", tree_sitter_$name, q_$name, \"$aliases\"},"; done
	echo '};'
	echo 'const int sigil_ngrammars = sizeof sigil_grammars / sizeof *sigil_grammars;'
} > "$gen.tmp"
cmp -s "$gen.tmp" "$gen" && rm "$gen.tmp" || mv "$gen.tmp" "$gen"

# objects: "<source> <object>" pairs; rebuilt only when the source is newer
{
	echo "deps/tree-sitter/lib/src/lib.c build/obj/tree-sitter.o"
	langs | while read -r name repo rev sub aliases; do
		d="deps/g-$name/$sub/src"
		echo "$d/parser.c build/obj/$name-parser.o"
		[ -f "$d/scanner.c" ] && echo "$d/scanner.c build/obj/$name-scanner.o"
	done
} | while read -r c o; do [ "$o" -nt "$c" ] || echo "$c $o"; done > build/todo
if [ -s build/todo ]; then
	echo "compile $(wc -l < build/todo | tr -d ' ') files ($JOBS at a time)"
	export CC CFLAGS
	# BusyBox xargs may be built without -P; then compile one at a time
	P="-P $JOBS"; echo | xargs $P true 2>/dev/null || P=
	xargs $P -n 2 sh -c '$CC $CFLAGS -std=c11 -w -Ideps/tree-sitter/lib/include -Ideps/tree-sitter/lib/src -I"$(dirname "$0")" -c "$0" -o "$1"' < build/todo
fi
$CC $CFLAGS -std=c11 -Wall -Wextra -Ideps/tree-sitter/lib/include -o bin/sigil src/sigil.c "$gen" build/obj/*.o
echo "built bin/sigil ($(./bin/sigil --list | wc -l | tr -d ' ') languages)"
